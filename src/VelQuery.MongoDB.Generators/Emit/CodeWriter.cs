using System.Text;

namespace VelQuery.MongoDB.Generators.Emit;

/// <summary>
/// Minimal indented writer. Always emits <c>\n</c> line endings and four-space indentation so output is byte-for-byte
/// identical on every OS (VQ-FR-032).
/// </summary>
internal sealed class CodeWriter
{
    public const string GeneratedCodeAttribute = "[global::System.CodeDom.Compiler.GeneratedCode(\"VelQuery.MongoDB.Generators\", \"" + VelQueryMongoGenerator.Version + "\")]";

    private readonly StringBuilder _builder = new();
    private int _indent;

    public CodeWriter Line(string text = "")
    {
        if (text.Length > 0)
        {
            _builder.Append(' ', _indent * 4);
            _builder.Append(text);
        }

        _builder.Append('\n');
        return this;
    }

    public CodeWriter Open(string text)
    {
        Line(text);
        Line("{");
        _indent++;
        return this;
    }

    public CodeWriter Close(string suffix = "")
    {
        _indent--;
        Line("}" + suffix);
        return this;
    }

    public void Indent() => _indent++;

    public void Outdent() => _indent--;

    public override string ToString() => _builder.ToString();

    public static CodeWriter WithHeader()
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("// Generated by VelQuery.MongoDB.Generators. Do not edit; changes are lost when the file is regenerated.");
        writer.Line("#nullable enable");
        writer.Line();
        return writer;
    }
}
