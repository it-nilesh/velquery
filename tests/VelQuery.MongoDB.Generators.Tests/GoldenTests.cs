using System;
using System.IO;
using System.Linq;
using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace VelQuery.MongoDB.Generators.Tests;

/// <summary>
/// Pins generated source byte-for-byte (VQ-FR-032). Set <c>VELQUERY_UPDATE_GOLDEN=1</c> to rewrite the expected files
/// after an intentional output change, then review the diff.
/// </summary>
public sealed class GoldenTests
{
    public static TheoryData<string> Cases => new(nameof(GoldenCases.Find), nameof(GoldenCases.Aggregate), nameof(GoldenCases.Writes), nameof(GoldenCases.Single));

    [Theory]
    [MemberData(nameof(Cases))]
    public void Generated_source_matches_expected_files(string caseName)
    {
        var source = Source(caseName);
        var (result, output) = MongoGeneratorHarness.Run(MongoGeneratorHarness.Compile(source));

        Assert.Empty(result.Diagnostics);
        Assert.Empty(MongoGeneratorHarness.CompilerProblems(output));

        var directory = Path.Combine(SourceDirectory(), "Expected", caseName);
        var generated = result.GeneratedSources.OrderBy(s => s.HintName, StringComparer.Ordinal).ToArray();
        if (Environment.GetEnvironmentVariable("VELQUERY_UPDATE_GOLDEN") == "1")
        {
            if (Directory.Exists(directory))
            {
                Directory.Delete(directory, recursive: true);
            }

            Directory.CreateDirectory(directory);
            foreach (var file in generated)
            {
                File.WriteAllText(Path.Combine(directory, file.HintName), file.SourceText.ToString());
            }
        }

        var expectedFiles = Directory.GetFiles(directory, "*.cs").Select(Path.GetFileName).Order(StringComparer.Ordinal).ToArray();
        Assert.Equal(expectedFiles, generated.Select(g => g.HintName).ToArray());
        foreach (var file in generated)
        {
            Assert.Equal(File.ReadAllText(Path.Combine(directory, file.HintName)), file.SourceText.ToString());
        }
    }

    [Fact]
    public void Every_generated_file_has_header_nullable_context_and_unix_newlines()
    {
        foreach (var caseName in Cases.Select(c => (string)c.Data))
        {
            var (result, _) = MongoGeneratorHarness.Run(MongoGeneratorHarness.Compile(Source(caseName)));
            Assert.All(result.GeneratedSources, s =>
            {
                var text = s.SourceText.ToString();
                Assert.StartsWith("// <auto-generated/>\n", text, StringComparison.Ordinal);
                Assert.Contains("\n#nullable enable\n", text, StringComparison.Ordinal);
                Assert.DoesNotContain("\r", text, StringComparison.Ordinal);
            });
        }
    }

    [Fact]
    public void Arguments_inside_aggregation_expressions_are_wrapped_in_literal_and_query_values_are_not()
    {
        var (result, _) = MongoGeneratorHarness.Run(MongoGeneratorHarness.Compile(GoldenCases.Aggregate));
        var text = result.GeneratedSources.Single(s => s.HintName.EndsWith("OrderSummary.Mongo.g.cs", StringComparison.Ordinal)).SourceText.ToString();
        const string values = "global::VelQuery.MongoDB.Serialization.MongoBsonValues";

        Assert.Contains($"{{ \"CustomerId\", {values}.From(args.customerId) }}", text, StringComparison.Ordinal); // $match: literal
        Assert.Contains($"{values}.Literal({values}.From(args.minTotal))", text, StringComparison.Ordinal); // $expr
        Assert.Contains($"{{ \"Label\", {values}.Literal({values}.From(args.label)) }}", text, StringComparison.Ordinal); // $project
        Assert.Contains($"{{ \"$literal\", {values}.From(args.label) }}", text, StringComparison.Ordinal); // already literal: not doubled
        Assert.Contains($"{{ \"$limit\", {values}.From(args.take) }}", text, StringComparison.Ordinal); // integer stage argument
        Assert.DoesNotContain("Parse(\"{", text, StringComparison.Ordinal); // no runtime JSON parsing
        Assert.DoesNotContain("BsonDocument.Parse", text, StringComparison.Ordinal);
    }

    [Fact]
    public void Generated_contracts_compile_against_the_real_runtime_without_warnings()
    {
        var all = MongoGeneratorHarness.Compile(
            (GoldenCases.Find, "/src/A.cs"), (GoldenCases.Aggregate, "/src/B.cs"), (GoldenCases.Writes, "/src/C.cs"), (GoldenCases.Single, "/src/D.cs"));
        var (result, output) = MongoGeneratorHarness.Run(all);
        Assert.Empty(result.Diagnostics);
        Assert.Empty(MongoGeneratorHarness.CompilerProblems(output));
        var emit = output.Emit(Stream.Null);
        Assert.True(emit.Success, string.Join("\n", emit.Diagnostics));
    }

    [Fact]
    public void Running_twice_and_in_any_file_order_produces_identical_output()
    {
        static string[] Generate(params (string, string)[] sources)
        {
            var (result, _) = MongoGeneratorHarness.Run(MongoGeneratorHarness.Compile(sources));
            return result.GeneratedSources.Select(s => s.HintName + "\n" + s.SourceText).Order(StringComparer.Ordinal).ToArray();
        }

        var forward = Generate((GoldenCases.Find, "/src/A.cs"), (GoldenCases.Writes, "/src/B.cs"), (GoldenCases.Aggregate, "/src/C.cs"));
        var again = Generate((GoldenCases.Find, "/src/A.cs"), (GoldenCases.Writes, "/src/B.cs"), (GoldenCases.Aggregate, "/src/C.cs"));
        var reverse = Generate((GoldenCases.Aggregate, "/src/C.cs"), (GoldenCases.Writes, "/src/B.cs"), (GoldenCases.Find, "/src/A.cs"));
        Assert.Equal(forward, again);
        Assert.Equal(forward, reverse);
    }

    [Fact]
    public void Unrelated_edits_keep_every_step_cached()
    {
        const string unrelated = "namespace Sample.Other; public static class Helpers { public static int Twice(int v) => v * 2; }";
        var compilation = MongoGeneratorHarness.Compile((GoldenCases.Find, "/src/Contracts.cs"), (unrelated, "/src/Helpers.cs"));
        var driver = MongoGeneratorHarness.CreateDriver(trackSteps: true).RunGenerators(compilation);

        var helpers = compilation.SyntaxTrees.Single(t => t.FilePath == "/src/Helpers.cs");
        var edited = compilation
            .ReplaceSyntaxTree(helpers, CSharpSyntaxTree.ParseText(unrelated.Replace("v * 2", "v + v", StringComparison.Ordinal), MongoGeneratorHarness.ParseOptions, "/src/Helpers.cs"))
            .AddSyntaxTrees(CSharpSyntaxTree.ParseText("namespace Sample.Other; public sealed class Added { }", MongoGeneratorHarness.ParseOptions, "/src/Added.cs"));
        var result = driver.RunGenerators(edited).GetRunResult().Results.Single();

        foreach (var name in new[] { VelQueryMongoGenerator.TrackingNames.Contracts, VelQueryMongoGenerator.TrackingNames.Models, VelQueryMongoGenerator.TrackingNames.Documents })
        {
            Assert.All(result.TrackedSteps[name].SelectMany(s => s.Outputs), o => Assert.True(
                o.Reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged, $"{name}: {o.Reason}"));
        }
    }

    [Fact]
    public void Edit_above_a_contract_does_not_regenerate_its_source_but_a_relevant_edit_does()
    {
        var compilation = MongoGeneratorHarness.Compile((GoldenCases.Find, "/src/Contracts.cs"));
        var driver = MongoGeneratorHarness.CreateDriver(trackSteps: true).RunGenerators(compilation);
        var tree = compilation.SyntaxTrees.Single();

        var shifted = compilation.ReplaceSyntaxTree(tree, CSharpSyntaxTree.ParseText("// a comment\n" + GoldenCases.Find, MongoGeneratorHarness.ParseOptions, "/src/Contracts.cs"));
        var shiftedResult = driver.RunGenerators(shifted).GetRunResult().Results.Single();
        Assert.All(shiftedResult.TrackedSteps[VelQueryMongoGenerator.TrackingNames.Models].SelectMany(s => s.Outputs), o => Assert.True(
            o.Reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged, $"models: {o.Reason}"));

        var changed = compilation.ReplaceSyntaxTree(tree, CSharpSyntaxTree.ParseText(
            GoldenCases.Find.Replace("\"users\"", "\"members\"", StringComparison.Ordinal), MongoGeneratorHarness.ParseOptions, "/src/Contracts.cs"));
        var changedResult = driver.RunGenerators(changed).GetRunResult().Results.Single();
        Assert.Contains(changedResult.TrackedSteps[VelQueryMongoGenerator.TrackingNames.Models].SelectMany(s => s.Outputs), o => o.Reason == IncrementalStepRunReason.Modified);
    }

    private static string Source(string caseName) => (string)typeof(GoldenCases).GetField(caseName)!.GetValue(null)!;

    private static string SourceDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;
}
