using System;
using System.IO;
using System.Linq;
using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;
using VelQuery.Testing;
using Xunit;

namespace VelQuery.Generators.GoldenTests;

/// <summary>
/// Pins generated source byte-for-byte (VQ-FR-032). Set <c>VELQUERY_UPDATE_GOLDEN=1</c> to rewrite the expected files
/// after an intentional output change, then review the diff.
/// </summary>
public sealed class GoldenTests
{
    public static TheoryData<string> Cases => new(nameof(GoldenCases.RecordRow), nameof(GoldenCases.ClassRow), nameof(GoldenCases.Scalar),
        nameof(GoldenCases.Stream), nameof(GoldenCases.NonQuery), nameof(GoldenCases.StoredProcedure));

    [Theory]
    [MemberData(nameof(Cases))]
    public void Generated_source_matches_expected_files(string caseName)
    {
        var source = (string)typeof(GoldenCases).GetField(caseName)!.GetValue(null)!;
        var (result, output) = GeneratorHarness.Run(GeneratorHarness.Compile(source));

        Assert.Null(result.Exception);
        Assert.Empty(result.Diagnostics);
        Assert.Empty(GeneratorHarness.CompilerProblems(output));

        var directory = Path.Combine(SourceDirectory(), "Expected", caseName);
        var generated = result.GeneratedSources.OrderBy(s => s.HintName, StringComparer.Ordinal).ToArray();
        if (Environment.GetEnvironmentVariable("VELQUERY_UPDATE_GOLDEN") == "1")
        {
            if (Directory.Exists(directory))
            {
                Directory.Delete(directory, recursive: true);
            }

            Directory.CreateDirectory(directory);
            foreach (var file in generated)
            {
                File.WriteAllText(Path.Combine(directory, file.HintName), file.SourceText.ToString());
            }
        }

        var expectedFiles = Directory.GetFiles(directory, "*.cs").Select(Path.GetFileName).Order(StringComparer.Ordinal).ToArray();
        Assert.Equal(expectedFiles, generated.Select(g => g.HintName).ToArray());
        foreach (var file in generated)
        {
            var expected = File.ReadAllText(Path.Combine(directory, file.HintName));
            Assert.Equal(expected, file.SourceText.ToString());
        }
    }

    [Fact]
    public void Every_generated_file_has_header_and_nullable_context()
    {
        var all = typeof(GoldenCases).GetFields().Select(f => (string)f.GetValue(null)!).ToArray();
        foreach (var source in all)
        {
            var (result, _) = GeneratorHarness.Run(GeneratorHarness.Compile(source));
            Assert.All(result.GeneratedSources, s =>
            {
                var text = s.SourceText.ToString();
                Assert.StartsWith("// <auto-generated/>\n", text, StringComparison.Ordinal);
                Assert.Contains("\n#nullable enable\n", text, StringComparison.Ordinal);
                Assert.DoesNotContain("\r", text, StringComparison.Ordinal);
            });
        }
    }

    private static string SourceDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;
}
